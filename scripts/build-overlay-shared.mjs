import { build } from 'esbuild';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
const result = await build({
    absWorkingDir: root,
    entryPoints: ['public/js/overlay/index.js'],
    outfile: 'public/js/overlay-shared.js',
    bundle: true,
    format: 'iife',
    target: 'es2020',
    legalComments: 'none',
    banner: { js: "// Generated by scripts/build-overlay-shared.mjs. Edit public/js/overlay/ sources, then rebuild.\nif (!window.OverlayShared?.[Symbol.for('StreamPulse.OverlayShared')]) {" },
    footer: { js: '}' },
    write: !check
});

if (check) {
    for (const file of result.outputFiles) {
        const current = await readFile(file.path, 'utf8').catch(() => '');
        if (current.replace(/\r\n/g, '\n') !== file.text.replace(/\r\n/g, '\n')) throw new Error(`Stale overlay bundle: ${resolve(root, file.path)}. Run node scripts/build-overlay-shared.mjs.`);
    }
}
