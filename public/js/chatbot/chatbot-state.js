let _extrasLoaded = false;
export const refreshStatus = () => fetch('/api/status', { cache: 'no-store' }).then(r => r.json()).then(async s => {
    liveStatus = s;
    if (!_extrasLoaded && window.OverlayShared?.loadLiveExtras) {
        _extrasLoaded = true;
        try { await window.OverlayShared.loadLiveExtras(s); } catch {}
    }
}).catch(() => {});

